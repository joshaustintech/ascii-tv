#!/usr/bin/env python3
"""Bakes Natural Earth land outlines into GlobeCore's land mask.

    python3 Scripts/bake_landmask.py path/to/ne_50m_land.geojson

Input: ne_50m_land.geojson from Natural Earth (public domain, naturalearthdata.com), e.g.
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson
Output: GlobeCore/Sources/GlobeCore/LandMaskData.swift, a 720x360 bitmap (half-degree squares, row 0 at the
north pole, column 0 at 180W, one bit per square, most significant bit first), base64 encoded.
"""
import base64
import json
import os
import sys

COLS, ROWS = 720, 360


def rings(geojson):
    for feature in geojson["features"]:
        g = feature["geometry"]
        polygons = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for polygon in polygons:
            yield from polygon


def bake(path):
    with open(path) as f:
        edges = []
        for ring in rings(json.load(f)):
            for (x0, y0), (x1, y1) in zip(ring, ring[1:]):
                if y0 != y1:
                    edges.append((x0, y0, x1, y1) if y0 < y1 else (x1, y1, x0, y0))

    bits = bytearray(COLS * ROWS // 8)
    for row in range(ROWS):
        lat = 90 - (row + 0.5) * 0.5
        # Even-odd scanline fill: a square is land when its centre is inside an odd number of rings.
        crossings = sorted(x0 + (lat - y0) * (x1 - x0) / (y1 - y0) for x0, y0, x1, y1 in edges if y0 <= lat < y1)
        for a, b in zip(crossings[0::2], crossings[1::2]):
            first = max(0, int((a + 180) * 2 + 0.5))
            last = min(COLS, int((b + 180) * 2 + 0.5))
            for col in range(first, last):
                i = row * COLS + col
                bits[i // 8] |= 0x80 >> (i % 8)
    return bytes(bits)


def main():
    data = base64.b64encode(bake(sys.argv[1])).decode()
    lines = [data[i:i + 120] for i in range(0, len(data), 120)]
    out = os.path.join(os.path.dirname(__file__), "..", "GlobeCore", "Sources", "GlobeCore", "LandMaskData.swift")
    with open(out, "w") as f:
        f.write("// Generated by Scripts/bake_landmask.py from Natural Earth 1:50m land (public domain). Do not edit.\n")
        f.write("enum LandMaskData {\n    static let naturalEarthBase64 = \"\"\"\n")
        f.write("\\\n".join(f"        {line}" for line in lines) + "\n")
        f.write("        \"\"\"\n}\n")
    print(f"wrote {out}: {len(data)} base64 characters")


if __name__ == "__main__":
    main()
